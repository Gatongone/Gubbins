using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Gubbins.Graphic.Kernels;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Gubbins.Graphic.Generator;

/// <summary>
/// Reads the methods marked <c>[GpuKernel]</c> and generates the typed entry point beside each of them, so that a kernel
/// is called the way any other method of the code base is.
/// </summary>
/// <remarks>
/// <para>
/// The generator is also the place the subset is checked: it translates every kernel while the program compiles, so a
/// construct the device cannot run is an error in the editor rather than a message from a build step that runs after it.
/// The translation is kept in the generated source as a constant, which the artifact build reads and hands to the
/// shading language compiler.
/// </para>
/// <para>
/// A kernel is declared in a partial type, because the entry point is a member of that type: <c>Motion.Run(gpu, source,
/// target)</c> sits beside <c>Motion.Integrate</c>, which is the method it dispatches.
/// </para>
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class KernelGenerator : IIncrementalGenerator
{
    /// <summary>
    /// The metadata name of the attribute that marks a kernel.
    /// </summary>
    private const string KERNEL_ATTRIBUTE = "Gubbins.Graphic.GpuKernelAttribute";

    /// <summary>
    /// The name of the file the generated source is added under.
    /// </summary>
    private const string HINT_NAME = "Gubbins.Kernels.g.cs";

    /// <summary>
    /// The descriptor of the error a kernel declared in a type that is not partial is reported with.
    /// </summary>
    private static readonly DiagnosticDescriptor NotPartial = new(
        "GUBBINS001",
        "A kernel is declared in a partial type",
        "The type '{0}' that declares the kernel '{1}' is not partial: the generated entry point is a member of it, so every type that holds the kernel is declared partial.",
        "Gubbins.Graphic",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>
    /// The descriptor of the error a kernel outside the subset is reported with.
    /// </summary>
    private static readonly DiagnosticDescriptor OutsideSubset = new(
        "GUBBINS002",
        "A kernel is inside the subset the device can run",
        "The kernel '{0}' cannot be translated: {1}",
        "Gubbins.Graphic",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <summary>
    /// The descriptor of the error a kernel of a shape the generated entry point does not cover is reported with.
    /// </summary>
    private static readonly DiagnosticDescriptor UnsupportedShape = new(
        "GUBBINS003",
        "A kernel takes one read only buffer and one writable buffer",
        "The kernel '{0}' does not take exactly one ReadOnlySpan<T> and one Span<T>: {1}",
        "Gubbins.Graphic",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var kernels = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                KERNEL_ATTRIBUTE,
                static (node, _) => node is MethodDeclarationSyntax,
                static (syntax, _) => (IMethodSymbol) syntax.TargetSymbol)
            .Collect();

        context.RegisterSourceOutput(
            context.CompilationProvider.Combine(kernels),
            static (production, pair) => Emit(production, pair.Left, pair.Right));
    }

    /// <summary>
    /// Generates the entry points of every kernel the compilation declares.
    /// </summary>
    /// <param name="context">The production context.</param>
    /// <param name="compilation">The compilation the kernels were resolved in.</param>
    /// <param name="kernels">The methods marked as kernels.</param>
    private static void Emit(SourceProductionContext context, Compilation compilation, ImmutableArray<IMethodSymbol> kernels)
    {
        if (kernels.IsDefaultOrEmpty)
        {
            return;
        }

        var source = new StringBuilder();
        var registry = new StringBuilder();

        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");

        registry.AppendLine("namespace Gubbins.Graphic.Generated");
        registry.AppendLine("{");
        registry.AppendLine("    internal static class __GubbinsKernels");
        registry.AppendLine("    {");

        var index = 0;

        foreach (var kernel in kernels.OrderBy(candidate => candidate.ToDisplayString(), StringComparer.Ordinal))
        {
            if (!Validate(context, kernel))
            {
                continue;
            }

            if (!TryTranslate(context, compilation, kernel, out var slang, out var threads))
            {
                continue;
            }

            var name = NameOf(kernel);

            WriteEntryPoint(source, kernel, name, threads);
            WriteRegistry(registry, index++, name, slang, threads);
        }

        registry.AppendLine("    }");
        registry.AppendLine("}");

        source.Append(registry);

        context.AddSource(HINT_NAME, SourceText.From(source.ToString(), Encoding.UTF8));
    }

    /// <summary>
    /// Checks that the kernel is declared where an entry point can be generated and has the shape the generated call
    /// takes.
    /// </summary>
    /// <param name="context">The production context.</param>
    /// <param name="kernel">The kernel.</param>
    /// <returns><see langword="true"/> when the kernel can be generated.</returns>
    private static bool Validate(SourceProductionContext context, IMethodSymbol kernel)
    {
        var location = kernel.Locations.FirstOrDefault();

        for (var type = kernel.ContainingType; type is not null; type = type.ContainingType)
        {
            if (!IsPartial(type))
            {
                context.ReportDiagnostic(Diagnostic.Create(NotPartial, location, type.ToDisplayString(), kernel.Name));
                return false;
            }
        }

        if (kernel.ContainingType.TypeKind != TypeKind.Class || kernel.ContainingType.IsGenericType)
        {
            context.ReportDiagnostic(Diagnostic.Create(
                UnsupportedShape,
                location,
                kernel.ToDisplayString(),
                "the type that declares it is a non generic class."));
            return false;
        }

        var buffers = kernel.Parameters.Where(parameter => parameter.Type is INamedTypeSymbol { Arity: 1 } named && (named.Name == "ReadOnlySpan" || named.Name == "Span")).ToList();

        if (buffers.Count != 2 || buffers[0].Type is not INamedTypeSymbol { Name: "ReadOnlySpan" } || buffers[1].Type is not INamedTypeSymbol { Name: "Span" })
        {
            context.ReportDiagnostic(Diagnostic.Create(
                UnsupportedShape,
                location,
                kernel.ToDisplayString(),
                "the generated entry point takes the buffers in the order the kernel declares them, so the kernel declares one ReadOnlySpan<T> and one Span<T>."));
            return false;
        }

        return true;
    }

    /// <summary>
    /// Translates one kernel, reporting the refusal the translator gave.
    /// </summary>
    /// <param name="context">The production context.</param>
    /// <param name="compilation">The compilation the kernel was resolved in.</param>
    /// <param name="kernel">The kernel.</param>
    /// <param name="slang">When the method returns, the Slang program.</param>
    /// <param name="threads">When the method returns, the threads in a group.</param>
    /// <returns><see langword="true"/> when the kernel was translated.</returns>
    private static bool TryTranslate(SourceProductionContext context, Compilation compilation, IMethodSymbol kernel, out string slang, out int threads)
    {
        slang = string.Empty;
        threads = 64;

        try
        {
            slang = KernelTranspiler.Transpile(compilation, kernel);
            threads = KernelTranspiler.ThreadsPerGroup(kernel);
            return true;
        }
        catch (KernelTranslationException exception)
        {
            context.ReportDiagnostic(Diagnostic.Create(OutsideSubset, kernel.Locations.FirstOrDefault(), kernel.ToDisplayString(), exception.Message));
            return false;
        }
    }

    /// <summary>
    /// Writes the entry point of one kernel into its type.
    /// </summary>
    /// <param name="source">The source being built.</param>
    /// <param name="kernel">The kernel.</param>
    /// <param name="name">The name the artifact is built under.</param>
    /// <param name="threads">The threads in a group.</param>
    private static void WriteEntryPoint(StringBuilder source, IMethodSymbol kernel, string name, int threads)
    {
        var type = kernel.ContainingType;
        var declared = new List<INamedTypeSymbol>();

        for (var current = type; current is not null; current = current.ContainingType)
        {
            declared.Insert(0, current);
        }

        var indent = 0;

        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            source.AppendLine($"namespace {type.ContainingNamespace.ToDisplayString()}");
            source.AppendLine("{");
            indent = 4;
        }

        foreach (var current in declared)
        {
            source.AppendLine($"{new string(' ', indent)}{Modifiers(current)} partial {Kind(current)} {current.Name}");
            source.AppendLine($"{new string(' ', indent)}{{");
            indent += 4;
        }

        var padding = new string(' ', indent);
        var sourceParameter = kernel.Parameters.First(parameter => parameter.Type is INamedTypeSymbol { Name: "ReadOnlySpan" });
        var targetParameter = kernel.Parameters.First(parameter => parameter.Type is INamedTypeSymbol { Name: "Span" });
        var element = ((INamedTypeSymbol) sourceParameter.Type).TypeArguments[0].ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var literal = SymbolDisplay.FormatLiteral(name, true);

        source.AppendLine();
        source.AppendLine($"{padding}/// <summary>");
        source.AppendLine($"{padding}/// Runs the kernel over the buffers this layer owns, and waits for it to finish.");
        source.AppendLine($"{padding}/// </summary>");
        source.AppendLine($"{padding}/// <param name=\"gpu\">The layer the kernel runs on.</param>");
        source.AppendLine($"{padding}/// <param name=\"{sourceParameter.Name}\">The buffer the kernel reads.</param>");
        source.AppendLine($"{padding}/// <param name=\"{targetParameter.Name}\">The buffer the kernel writes.</param>");
        source.AppendLine($"{padding}public static void Run(global::Gubbins.Graphic.Gpu gpu, global::Gubbins.Graphic.GpuBuffer<{element}> {sourceParameter.Name}, global::Gubbins.Graphic.GpuBuffer<{element}> {targetParameter.Name})");
        source.AppendLine($"{padding}{{");
        source.AppendLine($"{padding}    if (gpu is null)");
        source.AppendLine($"{padding}    {{");
        source.AppendLine($"{padding}        throw new global::System.ArgumentNullException(nameof(gpu));");
        source.AppendLine($"{padding}    }}");
        source.AppendLine();
        source.AppendLine($"{padding}    gpu.LoadKernel({literal}, {threads}).Run({sourceParameter.Name}, {targetParameter.Name});");
        source.AppendLine($"{padding}}}");
        source.AppendLine();
        source.AppendLine($"{padding}/// <summary>");
        source.AppendLine($"{padding}/// Runs the kernel over spans, staging them through buffers of this layer, and waits for it to finish.");
        source.AppendLine($"{padding}/// </summary>");
        source.AppendLine($"{padding}/// <param name=\"gpu\">The layer the kernel runs on.</param>");
        source.AppendLine($"{padding}/// <param name=\"{sourceParameter.Name}\">The values the kernel reads.</param>");
        source.AppendLine($"{padding}/// <param name=\"{targetParameter.Name}\">The span the kernel writes.</param>");
        source.AppendLine($"{padding}public static void Run(global::Gubbins.Graphic.Gpu gpu, global::System.ReadOnlySpan<{element}> {sourceParameter.Name}, global::System.Span<{element}> {targetParameter.Name})");
        source.AppendLine($"{padding}{{");
        source.AppendLine($"{padding}    if (gpu is null)");
        source.AppendLine($"{padding}    {{");
        source.AppendLine($"{padding}        throw new global::System.ArgumentNullException(nameof(gpu));");
        source.AppendLine($"{padding}    }}");
        source.AppendLine();
        source.AppendLine($"{padding}    using (var __source = gpu.Upload({sourceParameter.Name}))");
        source.AppendLine($"{padding}    using (var __target = gpu.Allocate<{element}>({targetParameter.Name}.Length))");
        source.AppendLine($"{padding}    {{");
        source.AppendLine($"{padding}        gpu.LoadKernel({literal}, {threads}).Run(__source, __target);");
        source.AppendLine($"{padding}        __target.CpuSpan.CopyTo({targetParameter.Name});");
        source.AppendLine($"{padding}    }}");
        source.AppendLine($"{padding}}}");

        for (var current = declared.Count - 1; current >= 0; current--)
        {
            indent -= 4;
            source.AppendLine($"{new string(' ', indent)}}}");
        }

        if (!type.ContainingNamespace.IsGlobalNamespace)
        {
            source.AppendLine("}");
        }
    }

    /// <summary>
    /// Writes the constants of one kernel into the registry the artifact build reads.
    /// </summary>
    /// <param name="registry">The registry being built.</param>
    /// <param name="index">The position of the kernel, which makes the type name unique.</param>
    /// <param name="name">The name the artifact is built under.</param>
    /// <param name="slang">The Slang program.</param>
    /// <param name="threads">The threads in a group.</param>
    private static void WriteRegistry(StringBuilder registry, int index, string name, string slang, int threads)
    {
        registry.AppendLine($"        internal static class Kernel{index}");
        registry.AppendLine("        {");
        registry.AppendLine($"            internal const string Name = {SymbolDisplay.FormatLiteral(name, true)};");
        registry.AppendLine($"            internal const int Threads = {threads};");
        registry.AppendLine($"            internal const string Slang = {SymbolDisplay.FormatLiteral(slang, true)};");
        registry.AppendLine("        }");
        registry.AppendLine();
    }

    /// <summary>
    /// Reads the name the artifact of a kernel is built under.
    /// </summary>
    /// <param name="kernel">The kernel.</param>
    /// <returns>The fully qualified type name and the method name, separated by dots.</returns>
    private static string NameOf(IMethodSymbol kernel)
        => kernel.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat).Replace("global::", string.Empty) + "." + kernel.Name;

    /// <summary>
    /// Reports whether a type is declared partial.
    /// </summary>
    /// <param name="type">The type.</param>
    /// <returns><see langword="true"/> when one of its declarations says so.</returns>
    private static bool IsPartial(INamedTypeSymbol type)
        => type.DeclaringSyntaxReferences.Any(reference =>
            reference.GetSyntax() is TypeDeclarationSyntax declaration &&
            declaration.Modifiers.Any(SyntaxKind.PartialKeyword));

    /// <summary>
    /// Writes the modifiers a partial declaration of a type has to repeat.
    /// </summary>
    /// <param name="type">The type.</param>
    /// <returns>The modifiers.</returns>
    private static string Modifiers(INamedTypeSymbol type)
    {
        var modifiers = new StringBuilder(type.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Private => "private",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            Accessibility.ProtectedAndInternal => "private protected",
            _ => "internal",
        });

        if (type.IsStatic)
        {
            modifiers.Append(" static");
        }
        else
        {
            if (type.IsAbstract)
            {
                modifiers.Append(" abstract");
            }

            if (type.IsSealed)
            {
                modifiers.Append(" sealed");
            }
        }

        return modifiers.ToString();
    }

    /// <summary>
    /// Writes the kind of a type.
    /// </summary>
    /// <param name="type">The type.</param>
    /// <returns>The keyword.</returns>
    private static string Kind(INamedTypeSymbol type)
        => type.TypeKind == TypeKind.Struct ? "struct" : "class";
}
